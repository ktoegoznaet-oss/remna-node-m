#!/usr/bin/env bash
# ============================================================================
#  Развёртывание ноды с нуля.
#
#    sudo ./scripts/install.sh
#
#  Что делает:
#    1. ставит docker, если его нет;
#    2. проверяет, что .env заполнен;
#    3. генерирует nginx.conf и xray-config.json из шаблонов;
#    4. поднимает контейнеры;
#    5. запускает диагностику.
#
#  Чего НЕ делает: не трогает фаервол и sysctl — это отдельные скрипты,
#  запускаются осознанно (scripts/firewall.sh, scripts/tune-sysctl.sh).
# ============================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

RED=$'\033[31m'; GREEN=$'\033[32m'; YELLOW=$'\033[33m'; BOLD=$'\033[1m'; OFF=$'\033[0m'
die()  { echo "${RED}ОШИБКА:${OFF} $*" >&2; exit 1; }
step() { echo; echo "${BOLD}==> $*${OFF}"; }

[[ $EUID -eq 0 ]] || die "нужны права root: sudo $0"

# ---------------------------------------------------------------------------
step "1/5 Docker"
# ---------------------------------------------------------------------------
if command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1; then
  echo "уже установлен: $(docker --version)"
else
  echo "ставлю docker с get.docker.com..."
  curl -fsSL https://get.docker.com | sh
  systemctl enable --now docker
fi

# ---------------------------------------------------------------------------
step "2/5 Конфигурация"
# ---------------------------------------------------------------------------
if [[ ! -f .env ]]; then
  cp .env.example .env
  chmod 600 .env
  cat <<MSG

${YELLOW}Создан .env из шаблона. Его нужно заполнить перед продолжением:${OFF}

  SECRET_KEY   — панель Remnawave -> Nodes -> Create node
  PANEL_IP     — IP сервера с панелью
  SNI_*        — три РАЗНЫХ маскировочных домена
  ключи Reality — ./scripts/gen-reality-keys.sh --write

Заполните .env и запустите этот скрипт снова.
MSG
  exit 0
fi
chmod 600 .env
echo ".env на месте"

# ---------------------------------------------------------------------------
step "3/5 Генерация конфигов"
# ---------------------------------------------------------------------------
./scripts/configure.sh

# ---------------------------------------------------------------------------
step "4/5 Запуск контейнеров"
# ---------------------------------------------------------------------------
docker compose pull
docker compose up -d
docker compose ps

# ---------------------------------------------------------------------------
step "5/5 Диагностика"
# ---------------------------------------------------------------------------
sleep 5
./scripts/check.sh || true

cat <<'NEXT'

Что осталось сделать руками:

  1. Вставить xray/xray-config.json в панель Remnawave и назначить профиль
     этой ноде.               -> docs/PANEL-SETUP.md
  2. Создать Hosts с портом 443 и правильными SNI/publicKey.
  3. Закрыть фаервол:          sudo ./scripts/firewall.sh
  4. По желанию, сетевой тюнинг: sudo ./scripts/tune-sysctl.sh

NEXT
